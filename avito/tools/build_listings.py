def item_line(it):
    name = ITEM_TEXT.get(it["name"], it["name"])
    brand = it.get("brand")
    if brand and brand not in name:
        name = f"{name} {brand}"
    if it["qty"]:
        name += f" {it['qty']}" if it["qty"].startswith("×") else f", {it['qty']}"
    return f"• {name}"


def grm_items(kit):
    if kit["drive"] == "цепь":
        return ["• Цепь ГРМ, натяжитель и успокоители — комплектом", "• Сальник коленвала", "• Герметик"]
    lines = ["• Ремень ГРМ и натяжной ролик — комплектом"]
    if "помпы" in kit["drive"]:
        lines.append("• Ремень привода помпы")
    return lines


def description(kit, n):
    parts = [INTRO[kit["sku"]], ""]
    parts.append("В коробке:")
    if kit["kind"] == "to":
        parts += [item_line(it) for it in kit["items"] if it["icon"] != "card"]
    else:
        parts += grm_items(kit)
    parts.append("• Карта ремонта с QR-видео")
    parts.append("")
    alt = ALTERNATIVES[n % len(ALTERNATIVES)]
    if kit["kind"] == "grm":
        parts += ["Если нужно, добавим помпу или масляный насос — посчитаем отдельно. " + alt, "",
                  "Работа ответственная — рекомендуем ставить в сервисе."]
    else:
        parts.append(alt)
    parts += ["", GUARANTEES[n % len(GUARANTEES)], "", SHIPPING, "", CTA[n % len(CTA)]]
    return "\n".join(parts)


